"""Real SGM stream checks without CERN, XFlow, SciPy, or DMD hardware."""

import builtins
from copy import deepcopy
import importlib
import json
from pathlib import Path
import unittest
from unittest.mock import patch

import numpy as np

from optidaq.data.pattern_stream import build_pattern_stream
from optidaq.extensions.sgm import dynamic_patterns


REFERENCE = Path(__file__).parent / "fixtures" / "sgm_xflow_reference.npz"


class DmdPatternStreamTest(unittest.TestCase):
    @staticmethod
    def recipe():
        return {
            "std_1": 0.06, "std_2": 0.11, "distribution": "other",
            "intensity_range": [0.07, 0.16], "center_radius_range": [0.0, 0.39],
            "aspect_range": [0.7, 1.55], "area_boost_scale": 0.0,
        }

    def test_matches_original_xflow_reference_frames(self):
        # Original XFlow outputs, not values generated by this module.
        # Provenance and input parameters are embedded in the small fixture.
        with np.load(REFERENCE, allow_pickle=False) as reference:
            metadata = json.loads(str(reference["_metadata"]))
            for name, params in metadata["cases"].items():
                with self.subTest(case=name):
                    original = deepcopy(params)
                    expected = reference[name]
                    stream = dynamic_patterns(**params)
                    actual = np.stack([next(stream) for _ in range(len(expected))])
                    self.assertEqual(params, original)
                    self.assertEqual(actual.dtype, np.float64)
                    np.testing.assert_allclose(actual, expected, rtol=1e-12, atol=1e-14)

    def test_seeded_streams_are_independent_and_leave_global_rng_unchanged(self):
        params = dict(canvas_size=[20, 24], num_gaussians=1, seed=17,
                      max_pixel_value=1.0, minimum_pixel_threshold=0.02,
                      update=self.recipe())
        baseline = dynamic_patterns(**params)
        expected = [next(baseline) for _ in range(4)]
        saved_state = np.random.get_state()
        try:
            np.random.seed(2026)
            before = np.random.get_state()
            stream = dynamic_patterns(**params)
            unrelated = dynamic_patterns(**dict(params, seed=99))
            actual = []
            for _ in range(4):
                next(unrelated)
                actual.append(next(stream))
                next(unrelated)
            after = np.random.get_state()
            self.assertEqual(before[0], after[0])
            np.testing.assert_array_equal(before[1], after[1])
            self.assertEqual(before[2:], after[2:])
        finally:
            np.random.set_state(saved_state)
        for image, repeated in zip(actual, expected):
            np.testing.assert_array_equal(image, repeated)
        self.assertFalse(np.array_equal(actual[0], actual[1]))

    def test_real_main_config_produces_nonzero_uint8_without_xflow_or_scipy(self):
        config_path = Path(__file__).parents[1] / "configs" / "experiment_lab_v1.json"
        config = json.loads(config_path.read_text())
        original_specs = deepcopy(config["dmd"]["streams"])
        real_import = builtins.__import__

        def without_external_generator(name, *args, **kwargs):
            if name.split(".")[0] in {"xflow", "scipy"}:
                raise AssertionError("SGM must not import %s" % name)
            return real_import(name, *args, **kwargs)

        with patch("builtins.__import__", side_effect=without_external_generator):
            importlib.reload(importlib.import_module("optidaq.extensions.sgm"))
            module = importlib.reload(importlib.import_module("optidaq.data.pattern_stream"))
            stream = module.build_pattern_stream(
                config["dmd"]["streams"], seed=config["dmd"]["seed"],
            )
            frames = [next(stream) for _ in range(3)]
        self.assertEqual(config["dmd"]["streams"], original_specs)
        for stream_index, source_id, image in frames:
            self.assertEqual((stream_index, source_id), (0, None))
            self.assertEqual(image.shape, (256, 256))
            self.assertEqual(image.dtype, np.uint8)
            self.assertGreater(np.count_nonzero(image), 0)
            self.assertEqual(int(image.min()), 0)
        self.assertFalse(np.array_equal(frames[0][2], frames[1][2]))
        # Fixed amplitude scaling must not normalize every spot to full brightness.
        self.assertTrue(any(int(image.max()) < 255 for _, _, image in frames))

    def test_stream_transform_preserves_reference_brightness(self):
        with np.load(REFERENCE, allow_pickle=False) as reference:
            params = json.loads(str(reference["_metadata"]))["cases"]["main_sgm"]
            expected = reference["main_sgm"]
        spec = [{
            "name": "dynamic_patterns", "params": params,
            "transforms": [{"name": "to_uint8", "params": {"max_value": 0.16}}],
        }]
        stream = build_pattern_stream(spec, seed=0)
        for raw in expected:
            _, _, image = next(stream)
            np.testing.assert_array_equal(
                image, np.clip(np.rint(raw / 0.16 * 255.0), 0, 255).astype(np.uint8),
            )

    def test_invalid_dimensions_and_counts_are_rejected(self):
        cases = [
            (None, 1), ([256], 1), ([256, 256, 1], 1), ("12", 1),
            ([0, 256], 1), ([256, -1], 1), ([True, 256], 1), ([8.5, 8], 1),
            ([8, 8], 0), ([8, 8], -1), ([8, 8], True), ([8, 8], 1.5),
        ]
        for shape, count in cases:
            with self.subTest(shape=shape, count=count):
                with self.assertRaises(ValueError):
                    next(dynamic_patterns(shape, count))


if __name__ == "__main__":
    unittest.main()
